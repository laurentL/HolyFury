-- Langue du client, l'anglais comble ce qui manque
local base = LOCALES.enUS
local current = LOCALES[GetLocale and GetLocale() or "enUS"] or base
local L = setmetatable({}, { __index = function(_, key)
    local v = current[key]
    if v == nil then v = base[key] end
    return v
end })

-- Mots de commande : ceux de toutes les langues sont acceptés
local aliases = {}
for _, loc in pairs(LOCALES) do
    if loc.CMD then
        for canonical, word in pairs(loc.CMD) do aliases[word] = canonical end
    end
end
aliases["déplacer"] = "move"
aliases["spé"] = "spec"

ns.L = L
ns.CMD_ALIASES = aliases
ns.LOCALES = LOCALES
